/**
 * Defines the hierarchical structure of the documentation sidebar.
 * Document IDs referenced here must map directly to Markdown filenames within `/docs`.
 */
import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';
import devicesData from './src/data/devices-metadata.json';
import {
  formatMergedDeviceLabel,
  type DeviceEntry,
} from './src/utils/deviceGrouping';

const devices: readonly DeviceEntry[] = devicesData;

/** Groups device links by shared firmware anchor. */
function getFirmwareLinks(predicate: (d: DeviceEntry) => boolean) {
  const groups = new Map<string, DeviceEntry[]>();
  for (const d of devices.filter(predicate)) {
    const targetId = d.folder || d.codename;
    const group = groups.get(targetId);
    if (group) {
      group.push(d);
    } else {
      groups.set(targetId, [d]);
    }
  }

  return Array.from(groups.entries()).map(([targetId, group]) => ({
    type: 'link' as const,
    label: formatMergedDeviceLabel(group),
    href: `/docs/firmware#${targetId}`,
  }));
}

const sidebars: SidebarsConfig = {
  mainSidebar: [
    {
      type: 'category',
      label: 'About the Project',
      collapsible: false,
      items: [
        'intro',
        'mentions',
        'contributing',
        'acknowledgements',
        'licensing',
      ],
    },
    {
      type: 'category',
      label: 'Resources',
      collapsible: false,
      items: [
        {
          type: 'category',
          label: 'Firmware',
          link: {
            type: 'doc',
            id: 'firmware',
          },
          collapsed: true,
          items: [
            {
              type: 'category',
              label: 'Nothing Phone Series',
              items: getFirmwareLinks((d) => d.brand === 'Nothing' && d.series === 'number'),
            },
            {
              type: 'category',
              label: 'Nothing Phone (a) Series',
              items: getFirmwareLinks((d) => d.brand === 'Nothing' && d.series === 'a'),
            },
            {
              type: 'category',
              label: 'Nothing Phone (b / Lite) Series',
              items: getFirmwareLinks((d) => d.brand === 'Nothing' && d.series === 'b'),
            },
            {
              type: 'category',
              label: 'CMF by Nothing Phone Series',
              items: getFirmwareLinks((d) => d.brand === 'CMF' || d.series === 'cmf'),
            },
          ],
        },
        {
          type: 'link',
          label: 'Community Apps & Projects',
          href: '/showcase',
        },
        'guides',
        {
          type: 'category',
          label: 'OTA Changelogs',
          link: {
            type: 'doc',
            id: 'changelogs/index',
          },
          items: [{ type: 'autogenerated', dirName: 'changelogs' }],
        },
        'official',
        'devices',
        'photography',
        {
          type: 'category',
          label: 'Community Archives',
          collapsed: true,
          items: ['apps', 'projects'],
        },
      ],
    },
  ],
};

export default sidebars;
